// Copies @near-wallet-selector/modal-ui/styles.css into src/lib/near/wallet-modal.css without its
// remote `@import` of Google Fonts (a blocked font request makes the lazy CSS chunk fail to load,
// which would break sign-in) and with the app's font. Run after upgrading modal-ui:
//   node scripts/sync-wallet-modal-css.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const pkg = require("@near-wallet-selector/modal-ui/package.json");
const src = readFileSync(require.resolve("@near-wallet-selector/modal-ui/styles.css"), "utf8");
const css = src
  .replace(/^@import\s+url\([^)]*\);?\s*$/gm, "")
  .replace(/font-family:\s*Inter,\s*sans-serif;/g, "font-family: var(--font-sans), sans-serif;");
if (/@import/.test(css)) throw new Error("Unexpected @import left in modal-ui styles");
writeFileSync(
  new URL("../src/lib/near/wallet-modal.css", import.meta.url),
  `/* Generated by scripts/sync-wallet-modal-css.mjs from @near-wallet-selector/modal-ui@${pkg.version}. Do not edit. */\n${css.trimStart()}`,
);
console.log(`wallet-modal.css synced from modal-ui@${pkg.version}`);
